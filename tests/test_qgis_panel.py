def core(module: str):
    """The core package as shipped inside the plugin.

    The tests also have the repository's copy on sys.path, and a class from one copy is not
    the same class as in the other. Anything the plugin must recognise (exceptions, configs)
    has to come from the plugin's own copy, as it does in a real install.
    """

    import importlib

    return importlib.import_module(f"fao_niger_agroclimate.agroclimate_core.{module}")


class FakeMessageBar:
    def __init__(self):
        self.messages = []

    def pushMessage(self, title, text, level=None, duration=None):
        self.messages.append((str(text), level))


class FakeIface:
    def __init__(self):
        from qgis.gui import QgsMapCanvas

        self.bar = FakeMessageBar()
        self.canvas = QgsMapCanvas()
        self.menu, self.toolbar, self.docks = [], [], []

    def mainWindow(self):
        return None

    def messageBar(self):
        return self.bar

    def mapCanvas(self):
        return self.canvas

    def addPluginToMenu(self, _menu, action):
        self.menu.append(action)

    def removePluginMenu(self, _menu, action):
        self.menu.remove(action)

    def addToolBarIcon(self, action):
        self.toolbar.append(action)

    def removeToolBarIcon(self, action):
        if action in self.toolbar:  # QGIS also tolerates removing an icon that was never added
            self.toolbar.remove(action)

    def addDockWidget(self, _area, dock):
        self.docks.append(dock)

    def removeDockWidget(self, dock):
        self.docks.remove(dock)


class FakePrompter:
    def __init__(self, answer: bool = True):
        self.answer, self.confirmations, self.warnings = answer, [], []
        self.exposure_choice, self.exposure_prompts = "test", 0  # "prepare", "test" or "cancel"

    def choose_exposure_action(self, from_acmad: bool = False):
        self.exposure_prompts += 1
        self.last_from_acmad = from_acmad
        return self.exposure_choice

    def confirm(self, title, text):
        self.confirmations.append((title, text))
        return self.answer

    def warn(self, title, text):
        self.warnings.append((title, text))


def run_inline(task):
    """Run a task synchronously the way QGIS would: work off-thread, finished on the main thread."""

    task.finished(task.run())


class PanelTestCase(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        qgis_support.init_qgis()
        qgis_support.load_plugin_package()

    def setUp(self):
        from qgis.PyQt.QtCore import QSettings
        from qgis.core import QgsProject, QgsSettings

        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        QgsProject.instance().clear()
        from fao_niger_agroclimate.controller import RiskPanelController
        from fao_niger_agroclimate.settings import PluginSettings

        self.store = QgsSettings(str(self.root / "settings.ini"), QSettings.IniFormat)
        self.settings = PluginSettings(self.store)
        self.settings.output_root = self.root / "out"
        self.settings.exposure_dir = self.root / "exposure"
        self.iface = FakeIface()
        self.prompter = FakePrompter(True)
        self.services, self.calls = fake_services(self.root, boundary=write_boundary(self.root / "b.geojson"))
        self.llm_calls = []
        self.llm_checks = []
        ConnectionReport = core("llm").ConnectionReport
        self.next_report = ConnectionReport(True, "Connected. The key works and the model 'm1' is available.")

        def fake_check(settings):
            self.llm_checks.append(settings)
            return self.next_report

        self.fake_llm_check = fake_check

        def fake_llm(settings, payload):
            self.llm_calls.append((settings, payload))
            return "Maradi stands out.\n\nDraft generated by a language model from the figures above. An expert must review it before use."

        self.controller = RiskPanelController(
            self.iface,
            Path(self.plugin_dir()),
            services=self.services,
            settings=self.settings,
            submit_task=run_inline,
            prompter=self.prompter,
            llm_request=fake_llm,
            llm_check=self.fake_llm_check,
        )
        self.dock = self.controller.dock
        self.RiskPanelController = RiskPanelController

    def plugin_dir(self) -> str:
        import fao_niger_agroclimate

        return str(Path(fao_niger_agroclimate.__file__).resolve().parent)

    def tearDown(self):
        from qgis.core import QgsProject

        self.controller.dispose()
        QgsProject.instance().clear()
        self.tmp.cleanup()

    def make_exposure(self):
        folder = self.root / "exposure"
        folder.mkdir(exist_ok=True)
        for name, value in (("cultivated_exposure.tif", 2.0), ("rangeland_exposure.tif", 1.0)):
            write_raster(folder / name, np.full((8, 8), value), cell=0.5, nodata=-9999.0)
        for name in ("cultivated_fraction.tif", "rangeland_fraction.tif"):
            write_raster(folder / name, np.full((4, 4), 0.5), nodata=-9999.0)
        self.dock.exposure_widget.setFilePath(str(folder))
        self.dock.refresh_exposure_status()
        return folder

    def run_current(self):
        """Type a date that ACMAD has not published yet, so the run falls back (the 'Other date' path)."""

        self.dock.current_radio.setChecked(True)
        self.dock.period_combo.setCurrentIndex(self.dock.period_combo.count() - 1)  # 'Other date...'
        self.dock.date_edit.setDate(self.dock.date_edit.date().__class__(2026, 10, 12))
        self.dock.output_widget.setFilePath(str(self.root / "out"))
        self.dock.run_button.click()

    def run_latest(self):
        """The default path: refresh the published periods and run with the first one selected."""

        self.controller.refresh_periods()
        self.dock.current_radio.setChecked(True)
        self.dock.output_widget.setFilePath(str(self.root / "out"))
        self.dock.run_button.click()


