class DisposeTests(PanelTestCase):
    def test_results_that_arrive_after_the_panel_is_closed_are_ignored(self):
        """A task finishing after the plugin was disabled must not touch the deleted panel."""

        held = []
        self.controller._submit = held.append  # capture the task instead of running it
        self.controller.refresh_periods()
        self.assertEqual(len(held), 1)

        self.controller.dispose()  # the user disables the plugin while the request is still running
        self.assertTrue(held[0].isCanceled())  # dispose asked the outstanding work to stop
        run_inline(held[0])  # the task still completes later; this must be a harmless no-op
        self.assertEqual(self.dock.period_combo.count(), 1)  # the panel was never filled

    def test_dispose_twice_is_safe(self):
        self.controller.dispose()
        self.controller.dispose()


