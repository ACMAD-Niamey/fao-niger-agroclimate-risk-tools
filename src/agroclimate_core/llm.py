"""Optional, off-by-default interpretation of a finished run by a language model.

The model only phrases results that the tools already computed. It never sets
a class, a threshold or a trigger, and it only ever receives the summary
numbers (never rasters, file paths or credentials). Anything it writes is a
draft for an expert to review; the disclaimer is added here, not by the model,
so it cannot be left out.

It speaks the widely supported OpenAI-style ``/chat/completions`` protocol, so
the same settings work for a hosted service or a local server.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from typing import Any, Dict, List, Mapping, Optional

import requests

logger = logging.getLogger(__name__)

DISCLAIMER = "Draft generated by a language model from the figures above. An expert must review it before use."
_LANGUAGES = {"en": "English", "fr": "French"}


class LlmError(RuntimeError):
    """The language model could not be used. Messages never contain the API key."""


@dataclass(frozen=True)
class LlmSettings:
    base_url: str = ""
    # repr=False keeps the key out of logs and tracebacks that print the settings.
    api_key: str = field(default="", repr=False)
    model: str = ""
    language: str = "en"
    timeout_seconds: float = 60.0

    @property
    def is_configured(self) -> bool:
        return bool(self.base_url.strip() and self.api_key.strip() and self.model.strip())


REGION_FIELDS = (
    "admin_name",
    "scored_area_km2",
    "mean_risk_score",
    "max_risk_class",
    "pct_low",
    "pct_moderate",
    "pct_high",
    "pct_very_high",
    "cultivated_ha_high_risk",
    "rangeland_ha_high_risk",
)
MAX_REGIONS_SENT = 15


def build_run_payload(
    *,
    period: str,
    hazard: str,
    fallback: bool,
    mask_applied: bool,
    statistics: Mapping[str, Any],
    regions: Optional[List[Mapping[str, Any]]] = None,
) -> Dict[str, Any]:
    """The only data a language model ever receives about a run.

    A fixed allow-list of summary figures: no file paths, no rasters, no user
    or machine details. What leaves the computer is exactly what is built here.
    """

    payload: Dict[str, Any] = {
        "period_shown": period,
        "hazard": "seasonal outlook (combined monitoring and forecast hazard)" if hazard == "combined_hazard" else "current drought indicator (CDI)",
        "older_than_requested": bool(fallback),
        "only_cropland_and_rangeland_scored": bool(mask_applied),
        "statistics": dict(statistics),
        "known_limitations": [
            "Class thresholds, exposure cut-offs and weights are provisional and under review.",
            "Blank areas were not scored; they are not low risk.",
            "The seasonal hazard is a 1 degree product, so its cells are about 110 km wide.",
        ],
    }
    if regions:
        payload["regions"] = [{key: row.get(key) for key in REGION_FIELDS} for row in regions[:MAX_REGIONS_SENT]]
    return payload


def _endpoint(base_url: str) -> str:
    url = base_url.strip().rstrip("/")
    return url if url.endswith("/chat/completions") else url + "/chat/completions"


def build_messages(payload: Mapping[str, Any], *, language: str = "en") -> List[Dict[str, str]]:
    """The chat messages for one run. ``payload`` is plain summary data."""

    language_name = _LANGUAGES.get(language, "English")
    system = (
        "You help technical staff at FAO Niger read an agropastoral drought risk map built from ACMAD "
        "drought products and land cover. Write a short, plain summary (under 200 words) for a "
        f"colleague, in {language_name}.\n"
        "Rules:\n"
        "- Use only the numbers in the data you are given. Do not invent figures, places or causes.\n"
        "- Say which period the map shows, and mention it plainly if the data is older than requested.\n"
        "- Say that class thresholds and weights are provisional and under review.\n"
        "- Describe where risk is highest and how much cropland or rangeland is affected, if given.\n"
        "- Do not give operational orders or predict losses; point to monitoring and expert review.\n"
    )
    user = "Run summary (JSON):\n" + json.dumps(payload, indent=2, default=str, ensure_ascii=False)
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def request_interpretation(
    settings: LlmSettings,
    payload: Mapping[str, Any],
    *,
    session: Optional[requests.Session] = None,
) -> str:
    """Ask the configured model to describe the run; returns text ending with the disclaimer."""

    if not settings.is_configured:
        raise LlmError("The language model is not configured: set the address, key and model first.")

    client = session or requests.Session()
    try:
        response = client.post(
            _endpoint(settings.base_url),
            headers={"Authorization": f"Bearer {settings.api_key}", "Content-Type": "application/json"},
            json={
                "model": settings.model,
                "messages": build_messages(payload, language=settings.language),
                "temperature": 0.2,
            },
            timeout=settings.timeout_seconds,
        )
    except requests.RequestException as exc:
        raise LlmError(f"Could not reach the language model service: {type(exc).__name__}") from exc

    if response.status_code != 200:
        # The body is not echoed back: a service may include the key or request in its error text.
        raise LlmError(f"The language model service answered with HTTP {response.status_code}.")
    try:
        text = response.json()["choices"][0]["message"]["content"]
    except (ValueError, KeyError, IndexError, TypeError) as exc:
        raise LlmError("The language model service sent an answer in an unexpected format.") from exc
    if not isinstance(text, str) or not text.strip():
        raise LlmError("The language model service returned an empty answer.")
    return f"{text.strip()}\n\n{DISCLAIMER}"
