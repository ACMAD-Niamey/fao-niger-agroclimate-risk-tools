        self.assertNotIn("sk-secret-123", text)
        self.assertEqual(payload["period_shown"], "2026-09-11")
        self.assertTrue(payload["older_than_requested"])
        self.assertIn("Maradi stands out.", self.dock.interpretation_view.toPlainText())
        self.assertIn("expert must review", self.dock.interpretation_view.toPlainText())

